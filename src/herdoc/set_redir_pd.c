#include "../minishell.h"

void	set_redir_(int fd, int nb, int on)
{
	if ((nb == 2 || nb == 1) && on == 1)
		dup2(fd, 1);
	if ((nb == 3 || nb == 4) && on == 1)
		dup2(fd, 0);
}
